/**
 * Generates all 6 coaches with 20 seats each (total 120 seats).
 * Populates seats from approved passengers array.
 */
export function generateInitialCoaches(approvedPassengers: Passenger[]): Coach[] {
  const passengerMapBySeat = new Map<string, Passenger>();
  approvedPassengers.forEach((p) => {
    if (p.seatNumber) {
      passengerMapBySeat.set(p.seatNumber, p);
    }
  });

  return COACH_METADATA.map((meta, coachIdx) => {
    const seats: Seat[] = [];
    for (let i = 1; i <= meta.capacity; i++) {
      const globalSeatIndex = coachIdx * 20 + i;
      const seatNumber = `MUM-${String(globalSeatIndex).padStart(4, '0')}`;
      const passenger = passengerMapBySeat.get(seatNumber);
      
      const row = Math.ceil(i / 4); // 1 to 5
      const col = ((i - 1) % 4) + 1; // 1 to 4
      const side = col <= 2 ? 'left' : 'right';
      const position = col === 1 || col === 4 ? 'window' : 'aisle';

      seats.push({
        id: `seat-${seatNumber}`,
        seatNumber,
        seatIndex: globalSeatIndex,
        coachId: meta.id,
        coachName: meta.name,
        row,
        col,
        side,
        position,
        status: passenger ? 'reserved' : 'available',
        passengerId: passenger?.id,
        passenger,
      });
    }

    return {
      ...meta,
      seats,
    };
  });
}
