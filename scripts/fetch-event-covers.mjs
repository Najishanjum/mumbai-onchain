// Downloads each event's cover image (its link's og:image, e.g. the Luma cover)
// into public/images/events/ and writes src/data/eventCovers.ts.
// Run after adding events: `npm run covers` (add --force to refetch all).
import sharp from 'sharp';
import { mkdir, readFile, writeFile, access } from 'node:fs/promises';

const OUT_DIR = 'public/images/events';
const MAP_FILE = 'src/data/eventCovers.ts';
const FORCE = process.argv.includes('--force');
const UA = 'Mozilla/5.0 (Macintosh; Intel Mac OS X 14_0) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Safari/605.1.15';

const source = await readFile('src/data/events.ts', 'utf8');
// Each event object has `id: '...'` before its `officialUrl: '...'`.
const events = [...source.matchAll(/id:\s*'([^']+)'[\s\S]*?officialUrl:\s*'([^']+)'/g)].map(([, id, url]) => ({ id, url }));

const exists = (p) => access(p).then(() => true, () => false);

function findImage(html, base) {
  // Luma's og:image is its own share card (logo, title, RSVP button) with the
  // cover inset; the raw square cover is in the page data as cover_url.
  const luma = html.match(/"cover_url":"(https:\/\/images\.lumacdn\.com\/[^"]+)"/);
  if (luma) return luma[1];
  const metas = [
    /<meta[^>]+property=["']og:image(?::secure_url)?["'][^>]+content=["']([^"']+)["']/i,
    /<meta[^>]+content=["']([^"']+)["'][^>]+property=["']og:image["']/i,
    /<meta[^>]+name=["']twitter:image["'][^>]+content=["']([^"']+)["']/i,
    /<meta[^>]+content=["']([^"']+)["'][^>]+name=["']twitter:image["']/i,
  ];
  for (const re of metas) {
    const m = html.match(re);
    if (m) return new URL(m[1].replace(/&amp;/g, '&'), base).href;
  }
  return null;
}

async function fetchWithTimeout(url, ms = 20000) {
  const ctrl = new AbortController();
  const t = setTimeout(() => ctrl.abort(), ms);
  try {
    return await fetch(url, { headers: { 'User-Agent': UA, Accept: 'text/html,image/*;q=0.9,*/*;q=0.8' }, signal: ctrl.signal, redirect: 'follow' });
  } finally {
    clearTimeout(t);
  }
}

async function cover({ id, url }) {
  const file = `${OUT_DIR}/${id}.webp`;
  if (!FORCE && (await exists(file))) return { id, status: 'kept' };
  try {
    const page = await fetchWithTimeout(url);
    if (!page.ok) return { id, status: `page ${page.status}` };
    const img = findImage(await page.text(), page.url);
    if (!img) return { id, status: 'no og:image' };
    const res = await fetchWithTimeout(img);
    if (!res.ok) return { id, status: `image ${res.status}` };
    const buf = Buffer.from(await res.arrayBuffer());
    // ~800px is sharp on a phone and keeps each cover around 30–80 KB.
    await sharp(buf).rotate().resize(800, 800, { fit: 'inside', withoutEnlargement: true }).webp({ quality: 78 }).toFile(file);
    return { id, status: 'saved', from: new URL(img).host };
  } catch (e) {
    return { id, status: `error: ${e.name === 'AbortError' ? 'timeout' : e.message}` };
  }
}

await mkdir(OUT_DIR, { recursive: true });
const results = [];
for (let i = 0; i < events.length; i += 4) {
  results.push(...(await Promise.all(events.slice(i, i + 4).map(cover))));
}

const have = [];
for (const { id } of events) if (await exists(`${OUT_DIR}/${id}.webp`)) have.push(id);
const body = have.map((id) => `  '${id}': '/images/events/${id}.webp',`).join('\n');
await writeFile(
  MAP_FILE,
  `// Generated by scripts/fetch-event-covers.mjs. Do not edit by hand.\n` +
    `// Cover art for each event, taken from its official/Luma page.\n` +
    `export const EVENT_COVERS: Record<string, string> = {\n${body}\n};\n`
);

for (const r of results) console.log(`${r.status.padEnd(14)} ${r.id}${r.from ? `  (${r.from})` : ''}`);
console.log(`\n${have.length}/${events.length} events have a cover.`);
